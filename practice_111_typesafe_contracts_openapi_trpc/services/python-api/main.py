"""FastAPI Schedule Optimization Service for Practice 111.

Demonstrates Schema-First contract definition with Pydantic v2,
explicit operationId naming, and discriminated union error models.
"""

from datetime import datetime, timezone
from typing import Literal
from uuid import uuid4

from fastapi import FastAPI, HTTPException, status
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse
from pydantic import BaseModel, Field

app = FastAPI(
    title="Schedule Optimization Service",
    description="Mathematical schedule optimization service exposing OpenAPI 3.1 contracts.",
    version="1.0.0",
)

# CORS setup for Vite frontend (http://localhost:5173)
app.add_middleware(
    CORSMiddleware,
    allow_origins=[
        "http://localhost:5173",
        "http://127.0.0.1:5173",
    ],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# ==============================================================================
# Domain Schemas & Discriminated Error Models (Pydantic v2)
# ==============================================================================


class ScheduleAssignment(BaseModel):
    """Individual assigned shift slot generated by the solver."""

    slot_id: str = Field(description="Unique identifier for the scheduled shift slot")
    worker_id: str = Field(description="Assigned worker identifier")
    shift_name: str = Field(description="Designation of shift, e.g., 'Morning', 'Night'")
    day_offset: int = Field(ge=0, description="Day index from start of planning horizon")
    estimated_cost: float = Field(ge=0.0, description="Cost calculated by the solver for this shift")


class OptimizationRequest(BaseModel):
    """Parameters to trigger a schedule optimization job."""

    horizon_days: int = Field(
        ge=1,
        le=90,
        default=14,
        description="Planning horizon in days (1 to 90)",
    )
    workforce_capacity: int = Field(
        ge=1,
        le=500,
        default=25,
        description="Maximum concurrent staff available",
    )
    cost_weight: float = Field(
        ge=0.0,
        le=1.0,
        default=0.7,
        description="Weight assigned to cost reduction vs shift preference satisfaction (0.0 to 1.0)",
    )
    allow_consecutive_night_shifts: bool = Field(
        default=False,
        description="Whether workers can be assigned back-to-back night shifts",
    )


class OptimizationSuccessResponse(BaseModel):
    """Successful result returned after solver run."""

    status: Literal["COMPLETED", "QUEUED"] = "COMPLETED"
    job_id: str = Field(description="UUID string identifying the optimization execution")
    horizon_days: int = Field(description="Planning horizon applied")
    total_cost: float = Field(ge=0.0, description="Minimized total operational cost")
    solver_status: str = Field(description="Solver outcome: 'OPTIMAL', 'FEASIBLE', etc.")
    assignments: list[ScheduleAssignment] = Field(description="List of assigned shifts")
    created_at: str = Field(description="ISO-8601 timestamp of job completion")


# Discriminated Domain Error Schemas
class OptimizationConflictError(BaseModel):
    """HTTP 409 Conflict: returned when constraints produce an infeasible schedule."""

    code: Literal["SCHEDULE_CONFLICT"] = "SCHEDULE_CONFLICT"
    message: str = Field(description="Human-readable explanation of constraint infeasibility")
    conflicting_slots: list[str] = Field(
        default_factory=list,
        description="Identifiers of overlapping or unresolvable shift demands",
    )
    recommended_action: str = Field(
        description="Suggested remediation for the user or calling system"
    )


class OptimizationResourceExhaustedError(BaseModel):
    """HTTP 422: returned when requested capacity cannot satisfy mandatory coverage."""

    code: Literal["RESOURCE_EXHAUSTED"] = "RESOURCE_EXHAUSTED"
    message: str = Field(description="Explanation of capacity shortfall")
    required_workers: int = Field(description="Minimum workers needed to satisfy coverage")
    available_workers: int = Field(description="Worker capacity provided in request")


# In-memory store for demonstration
_JOBS_STORE: dict[str, OptimizationSuccessResponse] = {}


