@app.post(
    "/api/v1/optimize",
    response_model=OptimizationSuccessResponse,
    status_code=status.HTTP_200_OK,
    operation_id="create_optimization_job",
    summary="Submit Schedule Optimization Job",
    responses={
        status.HTTP_200_OK: {
            "model": OptimizationSuccessResponse,
            "description": "Schedule optimization solved successfully",
        },
        status.HTTP_409_CONFLICT: {
            "model": OptimizationConflictError,
            "description": "Constraints produce a schedule conflict or infeasibility",
        },
        status.HTTP_422_UNPROCESSABLE_CONTENT: {
            "model": OptimizationResourceExhaustedError,
            "description": "Workforce capacity is insufficient for the requested horizon",
        },
    },
)
async def create_optimization_job(request: OptimizationRequest):
    """Execute schedule optimization algorithm based on user constraints."""
    # Simulated domain conflict trigger:
    # If horizon_days > 30 and workforce_capacity < 10 without consecutive night shifts,
    # the problem is mathematically infeasible.
    if request.horizon_days > 30 and request.workforce_capacity < 10:
        return JSONResponse(
            status_code=status.HTTP_409_CONFLICT,
            content=OptimizationConflictError(
                code="SCHEDULE_CONFLICT",
                message=f"Workforce of {request.workforce_capacity} cannot cover {request.horizon_days} days without violating mandatory rest intervals.",
                conflicting_slots=["slot-day-14-night", "slot-day-15-morning"],
                recommended_action="Increase workforce_capacity >= 15 or enable allow_consecutive_night_shifts.",
            ).model_dump(),
        )

    if request.workforce_capacity < 3:
        return JSONResponse(
            status_code=status.HTTP_422_UNPROCESSABLE_CONTENT,
            content=OptimizationResourceExhaustedError(
                code="RESOURCE_EXHAUSTED",
                message="A minimum of 3 workers is required to maintain legal 8-hour shift rotations.",
                required_workers=3,
                available_workers=request.workforce_capacity,
            ).model_dump(),
        )

    # Generate synthetic solved schedule
    job_id = f"opt-{uuid4().hex[:8]}"
    assignments: list[ScheduleAssignment] = []
    base_cost = 1200.0 * request.horizon_days * (0.8 + 0.2 * request.cost_weight)

    for day in range(min(request.horizon_days, 7)):
        worker_idx = (day % request.workforce_capacity) + 1
        assignments.append(
            ScheduleAssignment(
                slot_id=f"slot-d{day}-morn",
                worker_id=f"worker-{worker_idx:02d}",
                shift_name="Morning (08:00 - 16:00)",
                day_offset=day,
                estimated_cost=150.0 + (day * 5),
            )
        )

    response = OptimizationSuccessResponse(
        status="COMPLETED",
        job_id=job_id,
        horizon_days=request.horizon_days,
        total_cost=round(base_cost, 2),
        solver_status="OPTIMAL",
        assignments=assignments,
        created_at=datetime.now(timezone.utc).isoformat(),
    )
    _JOBS_STORE[job_id] = response
    return response


@app.get(
    "/api/v1/jobs/{job_id}",
    response_model=OptimizationSuccessResponse,
    status_code=status.HTTP_200_OK,
    operation_id="get_optimization_job",
    summary="Retrieve Optimization Job by ID",
    responses={
        status.HTTP_200_OK: {
            "model": OptimizationSuccessResponse,
            "description": "Job found and returned",
        },
        status.HTTP_404_NOT_FOUND: {
            "description": "Job not found",
        },
    },
)
async def get_optimization_job(job_id: str):
    """Fetch status and assignments for a previously executed optimization job."""
    if job_id not in _JOBS_STORE:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Optimization job '{job_id}' not found.",
        )
    return _JOBS_STORE[job_id]


